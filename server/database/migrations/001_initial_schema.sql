-- Traducción PostgreSQL del esquema SQL Server que compartió el usuario.
-- Ejecutar conectado a una base PostgreSQL vacía de Asadero Duke's.
CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_completo varchar(120) NOT NULL,
  nombre_usuario varchar(50) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  rol varchar(20) NOT NULL CHECK (rol IN ('Administrador','Mesero','Cocina','Cajero')),
  estado varchar(10) NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Inactivo')),
  fecha_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias (
  id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) NOT NULL UNIQUE,
  descripcion varchar(255),
  estado varchar(10) NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Inactivo'))
);

CREATE TABLE IF NOT EXISTS productos (
  id_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  id_categoria integer NOT NULL REFERENCES categorias(id_categoria),
  descripcion varchar(255),
  precio numeric(10,2) NOT NULL CHECK (precio >= 0),
  imagen_url varchar(300),
  activo boolean NOT NULL DEFAULT true,
  fecha_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_productos_categoria ON productos(id_categoria);

CREATE TABLE IF NOT EXISTS pedidos (
  id_pedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_mesero integer NOT NULL REFERENCES usuarios(id_usuario),
  tipo_pedido varchar(20) NOT NULL CHECK (tipo_pedido IN ('Para llevar','Mesa')),
  numero_mesa integer,
  estado varchar(20) NOT NULL DEFAULT 'Pendiente'
    CHECK (estado IN ('Pendiente','En preparación','Listo','Entregado','Pagado','Cancelado')),
  observaciones varchar(300),
  fecha_hora_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  subtotal numeric(10,2) NOT NULL DEFAULT 0,
  total numeric(10,2) NOT NULL DEFAULT 0,
  CHECK ((tipo_pedido='Mesa' AND numero_mesa IS NOT NULL) OR (tipo_pedido='Para llevar' AND numero_mesa IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_pedidos_estado ON pedidos(estado);
CREATE INDEX IF NOT EXISTS ix_pedidos_fecha ON pedidos(fecha_hora_creacion);

CREATE TABLE IF NOT EXISTS detalle_pedido (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES productos(id_producto),
  nombre_producto varchar(120) NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(10,2) NOT NULL CHECK (precio_unitario >= 0),
  nota varchar(200),
  subtotal_detalle numeric(10,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_detalle_pedido ON detalle_pedido(id_pedido);

CREATE TABLE IF NOT EXISTS pagos (
  id_pago integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedidos(id_pedido),
  id_usuario_cajero integer NOT NULL REFERENCES usuarios(id_usuario),
  metodo_pago varchar(20) NOT NULL CHECK (metodo_pago IN ('Efectivo','Tarjeta','Transferencia')),
  monto_total numeric(10,2) NOT NULL,
  monto_recibido numeric(10,2),
  cambio numeric(10,2),
  referencia varchar(100),
  fecha_hora_pago timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_pagos_pedido ON pagos(id_pedido);
CREATE INDEX IF NOT EXISTS ix_pagos_fecha ON pagos(fecha_hora_pago);

CREATE TABLE IF NOT EXISTS cortes_caja (
  id_corte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES usuarios(id_usuario),
  fecha_hora_apertura timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_hora_cierre timestamp,
  fondo_inicial numeric(10,2) NOT NULL DEFAULT 0,
  total_efectivo numeric(10,2) NOT NULL DEFAULT 0,
  total_tarjeta numeric(10,2) NOT NULL DEFAULT 0,
  total_transferencia numeric(10,2) NOT NULL DEFAULT 0,
  total_ventas numeric(10,2) NOT NULL DEFAULT 0,
  efectivo_esperado numeric(10,2) NOT NULL DEFAULT 0,
  efectivo_contado numeric(10,2),
  diferencia numeric(10,2)
);
CREATE INDEX IF NOT EXISTS ix_cortes_usuario ON cortes_caja(id_usuario);

CREATE TABLE IF NOT EXISTS historial_estados_pedido (
  id_historial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
  estado varchar(20) NOT NULL,
  id_usuario integer NOT NULL REFERENCES usuarios(id_usuario),
  fecha_hora timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  comentario varchar(200)
);
